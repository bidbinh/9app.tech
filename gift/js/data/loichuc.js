/** Điền chỗ trống. xung: cách xưng (con, em, mình...). ten: cách gọi người nhận. */
export function dienLoi(mau, { ten = 'bạn', xung = 'mình' } = {}) {
  const hoa = (s) => s.charAt(0).toUpperCase() + s.slice(1);
  return String(mau).replace(/\{Toi\}/g, hoa(xung)).replace(/\{toi\}/g, xung).replace(/\{ten\}/g, ten)
    .replace(/(^|[.!?]\s+)(\p{Ll})/gu, (_, a, b) => a + b.toUpperCase()); // đầu câu luôn viết hoa, kể cả khi bắt đầu bằng tên "anh Hùng"
}

/** Danh sách lời chúc đã chuẩn hóa: [{t, nhan, cho, dip, giong}] cho dịp+giọng, lọc theo nhóm quan hệ. */
export const NHOM_DUOC_KINH = ['cha-me', 'thay-co'];
/** Chỉ ông bà, cha mẹ, bậc trên và thầy cô mới được "kính chúc"; còn lại (sếp, đồng nghiệp, bạn bè, chưa chọn người) dùng "chúc". */
export function haKinh(t) {
  return String(t).replace(/xin kính chúc/g, 'xin chúc').replace(/kính chúc/g, 'chúc').replace(/Kính chúc/g, 'Chúc');
}
export function layLoiChuc(dip, giong, nhomQuanHe = null) {
  const lop = Object.hasOwn(LOI_CHUC, dip) ? LOI_CHUC[dip] : {};
  const ds = (Object.hasOwn(lop, giong) ? lop[giong] : []).map((x) => (typeof x === 'string' ? { t: x } : x));
  const kinh = NHOM_DUOC_KINH.includes(nhomQuanHe);
  return ds.filter((x) => !x.cho || !nhomQuanHe || x.cho.includes(nhomQuanHe)).map((x) => ({ ...x, t: kinh ? x.t : haKinh(x.t), dip, giong }));
}

/** Tổng số lời chúc mẫu. */
export function demLoiChuc() {
  return Object.values(LOI_CHUC).reduce((n, d) => n + Object.values(d).reduce((m, ds) => m + ds.length, 0), 0);
}
